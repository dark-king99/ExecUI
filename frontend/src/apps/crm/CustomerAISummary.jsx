import { useApi } from "../../hooks/useApi";
import { crm } from "../../services/api";
import { SkeletonCard } from "../../components/ui/Skeleton";
import { RefreshCw, AlertTriangle } from "lucide-react";

export default function CustomerAISummary() {
  const {
    data: summaries,
    loading,
    error,
    refetch,
  } = useApi(() => crm.ai.summaries({}), [], { pollingInterval: 300000 });

  return (
    <div className="space-y-4 bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl p-6 shadow-sm">
      <div className="flex items-center justify-between">
        <div>
          <h3 className="font-semibold text-slate-900 dark:text-white">AI Customer Summaries</h3>
          <p className="text-sm text-slate-500">AI-generated overview based on unified CRM activity</p>
        </div>
        <button
          onClick={refetch}
          className="text-slate-400 hover:text-slate-600 dark:hover:text-slate-200 transition"
        >
          <RefreshCw size={15} />
        </button>
      </div>

      {error && (
        <div className="flex items-center gap-2 rounded-lg border border-red-200 dark:border-red-800 bg-red-50 dark:bg-red-900/20 px-3 py-2 text-sm text-red-700 dark:text-red-300">
          <AlertTriangle size={14} /> {error}
        </div>
      )}

      {loading ? (
        <div className="space-y-3">
          {Array.from({ length: 3 }).map((_, i) => <SkeletonCard key={i} />)}
        </div>
      ) : summaries?.length > 0 ? (
        summaries.map((item) => (
          <div
            key={item.id ?? item.customer}
            className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl p-6 shadow-sm space-y-2"
          >
            <p className="font-medium text-slate-900 dark:text-white">{item.customer}</p>
            <p className="text-sm text-slate-600 dark:text-slate-400 leading-relaxed">{item.summary}</p>
            <p className="text-xs text-slate-400">Generated by AI · CRM Insights</p>
          </div>
        ))
      ) : !loading && !error ? (
        <p className="text-sm text-slate-500 text-center py-4">No AI summaries available.</p>
      ) : null}
    </div>
  );
}
