import { useState } from "react";
import { Sparkles, Wand2, Mail, Share2, Megaphone, FileText, Loader2, Copy, Check } from "lucide-react";
import { useToast } from "../../../../components/ui/Toast";
import { useMutation } from "../../../../hooks/useApi";
import { marketing } from "../../../../services/api";
import { SolutionShell, Section, PrimaryBtn } from "../../components/mkt-ui";

const MODES = [
  { id: "content", label: "Content Brief", icon: FileText },
  { id: "campaign", label: "Campaign Plan", icon: Megaphone },
  { id: "social", label: "Social Pack", icon: Share2 },
  { id: "ads", label: "Ad Copy", icon: Mail },
];

export default function ContentGeneration() {
  const toast = useToast();
  const [mode, setMode] = useState("content");
  const [prompt, setPrompt] = useState("");
  const [result, setResult] = useState(null);
  const [copied, setCopied] = useState(false);
  const { mutate, loading } = useMutation((body) => marketing.ai.generate(body), {
    onSuccess: (r) => setResult(r),
    onError: (e) => toast({ message: e?.message ?? "Generation failed", type: "error" }),
  });

  const copy = () => {
    if (!result?.copy) return;
    navigator.clipboard?.writeText(result.copy);
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  };

  return (
    <SolutionShell solutionId="einstein" title="Content Generation" subtitle="Generate on-brand marketing content with Einstein">
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-4">
        <Section title="Prompt" subtitle="Describe what you need" icon={Wand2}>
          <div className="flex flex-wrap gap-1.5 mb-4">
            {MODES.map((m) => {
              const Icon = m.icon;
              return (
                <button key={m.id} onClick={() => setMode(m.id)} className={`flex items-center gap-1.5 text-xs px-2.5 py-1.5 rounded-lg border transition ${mode === m.id ? "bg-emerald-600 text-white border-emerald-600" : "border-slate-200 dark:border-slate-700 text-slate-600 dark:text-slate-300 hover:border-emerald-400"}`}>
                  <Icon size={13} /> {m.label}
                </button>
              );
            })}
          </div>
          <textarea value={prompt} onChange={(e) => setPrompt(e.target.value)} rows={5}
            placeholder="e.g. A product launch for our new analytics dashboard targeting mid-market RevOps leaders"
            className="w-full text-sm border border-slate-200 dark:border-slate-700 rounded-lg px-3 py-2 bg-white dark:bg-slate-800 text-slate-900 dark:text-white focus:outline-none focus:ring-2 focus:ring-emerald-500 resize-none" />
          <div className="mt-4">
            <PrimaryBtn color="emerald" disabled={loading} onClick={() => mutate({ mode, prompt })}>
              {loading ? <><Loader2 size={15} className="animate-spin" /> Generating…</> : <><Sparkles size={15} /> Generate</>}
            </PrimaryBtn>
          </div>
        </Section>

        <Section title={result?.title ?? "Output"} subtitle={result ? "Generated by Einstein" : "Your generated content will appear here"} icon={Sparkles}
          actions={result?.copy && <button onClick={copy} className="text-xs flex items-center gap-1 px-2.5 py-1 rounded-lg border border-slate-200 dark:border-slate-700 text-slate-600 dark:text-slate-300 hover:bg-slate-50 dark:hover:bg-slate-800 transition">{copied ? <><Check size={12} /> Copied</> : <><Copy size={12} /> Copy</>}</button>}>
          {!result ? (
            <div className="py-12 text-center text-sm text-slate-400">Enter a prompt and hit Generate.</div>
          ) : (
            <div className="space-y-4">
              <p className="text-sm text-slate-600 dark:text-slate-300">{result.summary}</p>
              {result.copy && <pre className="text-sm bg-slate-50 dark:bg-slate-800/60 rounded-lg p-4 whitespace-pre-wrap text-slate-700 dark:text-slate-200 leading-relaxed">{result.copy}</pre>}
              {result.steps?.length > 0 && (
                <div>
                  <h4 className="text-xs font-semibold uppercase tracking-wide text-slate-400 mb-2">Recommended Steps</h4>
                  <ol className="space-y-1.5">
                    {result.steps.map((s, i) => (
                      <li key={i} className="flex gap-2 text-sm text-slate-600 dark:text-slate-300">
                        <span className="h-5 w-5 rounded-full bg-emerald-100 dark:bg-emerald-900/40 text-emerald-700 dark:text-emerald-400 text-xs font-semibold flex items-center justify-center shrink-0">{i + 1}</span>
                        {s}
                      </li>
                    ))}
                  </ol>
                </div>
              )}
            </div>
          )}
        </Section>
      </div>
    </SolutionShell>
  );
}
